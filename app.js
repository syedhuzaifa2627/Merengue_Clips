const container = document.getElementById("videos");
const searchInput = document.getElementById("searchInput");
const searchButton = document.getElementById("searchButton")


function render(list) {
  container.innerHTML = list.map(e => `
    <div class="video-card">
      <img src="${e.thumb}" />
      <div class="video-info">
        <div class="avatar">${e.channel[0]}</div>
        <div>
          <h4>${e.title}</h4>
          <p>${e.channel}</p>
          <p>${e.views}</p>
        </div>
      </div>
    </div>
  `).join("")
}
const buttons = document.querySelectorAll(".chip")

buttons.forEach(function (button) {
  button.addEventListener("click", function () {

    buttons.forEach(function (btn) {
      btn.classList.remove("active")
    })
    button.classList.add("active")

    const category = button.innerText

    if (category === "All") {
      render(videoData);
    } else {
      const filteredVideos = videoData.filter(function (video) {
        return video.category === category
      })
      render(filteredVideos)
    }
  })
})

render(videoData)


function handleSearch() {
  const searchValue = searchInput.value.trim().toLowerCase()

  if (searchValue === "") {
    alert("😊 Start typing to search videos!")
    render(videoData)
    return
  }

  const searchedVideos = videoData.filter(video =>
    video.title.toLowerCase().includes(searchValue) ||
    video.channel.toLowerCase().includes(searchValue) ||
    video.category.toLowerCase().includes(searchValue)
  )

  render(searchedVideos)
}

searchButton.addEventListener("click", handleSearch)





